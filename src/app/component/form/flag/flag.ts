import {Component, Input} from '@angular/core';

//=============================================================================

@Component({
  selector: 'flag',
  templateUrl: './flag.html',
  styleUrls: [ './flag.scss'],
  imports: []
})

//=============================================================================

export class Flag {

  //-------------------------------------------------------------------------
  //---
  //--- Variables
  //---
  //-------------------------------------------------------------------------

  @Input() value? : boolean

  //-------------------------------------------------------------------------
  //---
  //--- Constructor
  //---
  //-------------------------------------------------------------------------

  constructor() {
  }

  //-------------------------------------------------------------------------
  //---
  //--- Helpers
  //---
  //-------------------------------------------------------------------------

  icon() : string {
    if (this.value == undefined) {
      return "question_mark"
    }

    return this.value ? "check" : "close";
  }

  //-------------------------------------------------------------------------

  style() : string {
    if (this.value == undefined) {
      return "#B09000"
    }

    return this.value ? "#00C000" : "#C00000"
  }
}

